/** The public motion catalogue: a package is checked against its SHA-256, unpacked without links or stray paths, and becomes the same pack the built-in copy is. */
import {test} from 'node:test';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {createServer} from 'node:http';
import {mkdirSync,mkdtempSync,readFileSync,symlinkSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {dirname,join} from 'node:path';
import {BUILTIN_MOTIONS,builtinMotion,inspectMotion} from '../../packages/ir/src/motions.ts';
import {hubMotion,packFromPackage,searchHub,untar,type HubMotion} from '../../packages/cli/src/motionhub.ts';
import {readFileSync as read,existsSync} from 'node:fs';

const AUTHORS = [{name: 'SuoSi', github: 'iamsuosi'}], LICENSE = {text: 'CC-BY-4.0', code: 'MIT'};
/** A colour as the format's tokens hold it (W3C design tokens) */
const dtcg = (hex: string) => ({$value: {colorSpace: 'srgb', components: [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255), hex}});

/**
 * The built-in `slug` in the catalogue's form, as motionhub.dev publishes it (its SPEC.md): motion.json, tokens.json from the theme, MOTION.md with the
 * format's headings, the poster, and the components under react/. `change` is applied to its directory; the index row comes with it.
 */
function hubPackage(slug: string, change: (root: string) => void = () => {}): {row: HubMotion; gz: Buffer} {
  // the catalogue names a motion @<scope>/<slug>, and its package holds it under that path
  const id = `@iamsuosi/${slug}`, dir = mkdtempSync(join(tmpdir(), 'hub-')), root = join(dir, id), pack = builtinMotion(slug)!;
  const own = JSON.parse(Buffer.from(pack.get('motion/motion.json')!).toString('utf8')), tokens = own.theme.tokens;
  const put = (path: string, data: string | Uint8Array) => { mkdirSync(dirname(join(root, path)), {recursive: true}); writeFileSync(join(root, path), data); };
  put('motion.json', JSON.stringify({spec: 'motion/0.4', scope: 'iamsuosi', slug, version: '1.0.1', name: own.name, line: {en: own.line.slice(0, 160)}, authors: AUTHORS, license: LICENSE,
    fit: {kind: 'general', for: {en: 'Explainers.'}}}));
  put('tokens.json', JSON.stringify({
    color: {$type: 'color', ...Object.fromEntries(Object.entries(tokens.colors as Record<string,string>).map(([k, v]) => [k, dtcg(v)]))},
    font: {$type: 'fontFamily', ...Object.fromEntries(Object.entries(tokens.fonts as Record<string,string>).map(([k, v]) => [k, {$value: v.split(',').map((f) => f.trim().replace(/^"|"$/g, ''))}]))},
  }));
  put('MOTION.md', Buffer.from(pack.get('motion/MOTION.md')!).toString('utf8').replace(/^<!-- Generated by visotalk[^\n]*\n/m, '').replace(/^## \d+\.\s+/gm, '## ')
    .replace(/^## Pitfalls\b/gm, '## Avoid: pitfalls').replace(/\(`parts\//g, '(`react/parts/'));
  put('poster.jpg', read(join(import.meta.dirname, '../../skills/visotalk/motions', slug, 'poster.jpg')));
  put('CREDITS.md', '# Credits\n\nOriginal.\n');
  for (const [path, data] of pack) if (/^motion\/((parts|assets|previews)\/|reel\.tsx$|sound\.json$)/.test(path)) put(`react/${path.slice('motion/'.length)}`, data);
  change(root);
  const gz = execFileSync('tar', ['-czf', '-', '-C', dir, id]);
  const row: HubMotion = {slug: id, version: '1.0.1', name: {en: 'Red Pencil'}, line: {en: 'A printed page marked up in red.'}, tags: ['hand-drawn', 'light'],
    authors: AUTHORS, license: LICENSE, poster: `/m/${id}/poster.jpg`, tools: existsSync(join(root, 'react')) ? ['react'] : [],
    package: {url: `/m/${id}/1.0.1.tgz`, sha256: createHash('sha256').update(gz).digest('hex'), bytes: gz.length},
    fit: {kind: 'general', for: {en: 'Checking a document line by line.'}}};
  return {row, gz};
}
const text = (pack: Map<string,Uint8Array>, path: string) => Buffer.from(pack.get(path)!).toString('utf8');
const config = (pack: Map<string,Uint8Array>) => JSON.parse(text(pack, 'motion/motion.json'));

test('a catalogue motion becomes a pack with the components, theme and guidance it was published with', () => {
  for (const slug of ['red-pencil', 'stage-light', 'on-air', 'field-atlas']) {
    const {row, gz} = hubPackage(slug);
    const pack = packFromPackage(row, gz), builtin = builtinMotion(slug)!;
    for (const [path, data] of builtin) if (/^motion\/(parts|assets|previews)\//.test(path)) assert.ok(Buffer.from(pack.get(path)!).equals(Buffer.from(data)), path);
    assert.ok(![...pack.keys()].some((p) => p.startsWith('motion/demo/')), 'no sample comes back');
    assert.equal(text(pack, 'motion/MOTION.md'), text(builtin, 'motion/MOTION.md').replace(/^<!-- Generated by visotalk[^\n]*\n/m, ''));
    const was = config(builtin).theme.tokens, now = config(pack).theme.tokens;
    assert.deepEqual(now.colors, was.colors, slug);
    assert.deepEqual(now.fonts, was.fonts, slug);
    assert.equal(config(pack).theme.id, config(builtin).theme.id, slug);
    assert.deepEqual(inspectMotion(pack).issues, [], slug);
  }
});

test('a catalogue motion without components is a theme and its guidance; a package is refused when its SHA-256, paths or entries are wrong', () => {
  const bare = hubPackage('red-pencil', (root) => {
    execFileSync('rm', ['-r', join(root, 'react')]);
    writeFileSync(join(root, 'MOTION.md'), '# Paper\n\n## Essence\nx\n## Colour\nx\n## Type\nx\n## Motion\nx\n## Avoid\nx\n');
  });
  const pack = packFromPackage(bare.row, bare.gz);
  assert.deepEqual([...pack.keys()].sort(), ['motion/MOTION.md', 'motion/motion.json', 'motion/poster.jpg']);
  assert.deepEqual(inspectMotion(pack).issues, []);
  const {row, gz} = hubPackage('red-pencil');
  assert.throws(() => packFromPackage({...row, package: {...row.package, sha256: '0'.repeat(64)}}, gz), /SHA-256/);
  const linked = hubPackage('red-pencil', (root) => symlinkSync('/etc/passwd', join(root, 'react', 'parts', 'link.tsx')));
  assert.throws(() => packFromPackage(linked.row, linked.gz), /link/);
  assert.throws(() => packFromPackage({...row, slug: 'another'}, gz), /outside its motion/);
});

test('untar reads a long path through the ustar prefix', () => {
  const dir = mkdtempSync(join(tmpdir(), 'long-')), path = `${'a'.repeat(70)}/${'b'.repeat(70)}/c.txt`;
  mkdirSync(join(dir, dirname(path)), {recursive: true});
  writeFileSync(join(dir, path), 'long');
  const tar = execFileSync('tar', ['--format=ustar', '-cf', '-', '-C', dir, path]);
  assert.equal(Buffer.from(untar(tar).get(path)!).toString(), 'long');
});

test('search matches every word against slugs, names, lines, what a motion is for and tags', () => {
  const {row} = hubPackage('red-pencil');
  assert.equal(searchHub([row], ['RED', 'light']).length, 1);
  assert.equal(searchHub([row], ['document', 'general']).length, 1);
  assert.equal(searchHub([row], ['red', 'dark']).length, 0);
  assert.equal(searchHub([row], []).length, 1);
});

test('a motion is fetched from the catalogue by its id; an unknown id is no motion', async () => {
  const {row, gz} = hubPackage('red-pencil');
  const server = createServer((req, res) => {
    if (req.url === '/api/motions.json') { res.setHeader('content-type', 'application/json'); res.end(JSON.stringify({spec: 'motion/0.1', motions: [row]})); }
    else if (req.url === row.package.url) res.end(gz);
    else { res.statusCode = 404; res.end(); }
  });
  await new Promise<void>((done) => server.listen(0, '127.0.0.1', done));
  const base = `http://127.0.0.1:${(server.address() as {port: number}).port}`;
  try {
    assert.deepEqual(inspectMotion((await hubMotion('@iamsuosi/red-pencil', base))!).issues, []);
    assert.equal(await hubMotion('@iamsuosi/no-such-motion', base), undefined);
    assert.equal(await hubMotion('red-pencil', base), undefined, 'the catalogue has no unscoped ids');
  } finally { server.close(); }
});

test('every built-in motion carries a reel the catalogue plays: a default export of 16 to 22 seconds', () => {
  for (const slug of BUILTIN_MOTIONS) {
    const reel = builtinMotion(slug)!.get('motion/reel.tsx');
    assert.ok(reel, `${slug} has no reel.tsx`);
    const text = Buffer.from(reel).toString('utf8');
    const seconds = Number(/export\s+const\s+reel\s*=\s*\{[^}]*\bseconds\s*:\s*([\d.]+)/.exec(text)?.[1]);
    assert.ok(/export\s+default\b/.test(text) && seconds >= 16 && seconds <= 22, `${slug}: reel.tsx needs a default export and 16 to 22 seconds (has ${seconds})`);
    assert.ok(!/from\s+['"]\.\.?\/(demo|\.\.)\//.test(text), `${slug}: a reel imports only ./parts, never the sample`);
    // and its sound: the motion's voices (sound.json) on the reel's cues, every cue inside the reel
    assert.ok(builtinMotion(slug)!.has('motion/sound.json'), `${slug} has no sound.json`);
    const cues = [...(/export\s+const\s+cues[^=]*=\s*\[([\s\S]*?)\];/.exec(text)?.[1] ?? '').matchAll(/at:\s*([\d.]+)/g)].map((m) => Number(m[1]));
    assert.ok(cues.length >= 6 && cues.every((at) => at >= 0 && at < seconds), `${slug}: reel.tsx needs \`export const cues\`, at least six, inside its ${seconds} s`);
  }
});
