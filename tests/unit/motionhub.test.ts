/** The public motion catalogue: a package is checked against its SHA-256, unpacked without links or stray paths, and becomes the same pack the built-in copy is. */
import {test} from 'node:test';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {createServer} from 'node:http';
import {mkdirSync,mkdtempSync,readFileSync,symlinkSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {dirname,join} from 'node:path';
import {builtinMotion,inspectMotion} from '../../packages/ir/src/motions.ts';
import {captionTokens,cssColor,cssShadow,hubMotion,nextVersion,packFromPackage,searchHub,shareMotion,toHub,untar,type HubMotion} from '../../packages/cli/src/motionhub.ts';
import {createRequire} from 'node:module';
import {readFileSync as read,existsSync} from 'node:fs';

// the catalogue's checker, resolved from the CLI's own dependency (the tests are outside the package), under any install layout
const {checkMotion} = await import(createRequire(join(import.meta.dirname, '../../packages/cli/package.json')).resolve('@motionhub/cli'));

/** A built-in pack with a poster, as a work's motion/ or a skills/visotalk/motions/<slug>/ directory holds it */
const withPoster = (slug: string) => new Map([...builtinMotion(slug)!, ['motion/poster.jpg', new Uint8Array(read(join(import.meta.dirname, '../../skills/visotalk/motions', slug, 'poster.jpg')))]]);
const ID = {authors: [{name: 'SuoSi', github: 'iamsuosi'}], license: {text: 'CC-BY-4.0', code: 'MIT'}, credit: 'Original.'};

/** The built-in `slug` as the catalogue publishes it (toHub), with `change` applied to its directory; and its index row */
function hubPackage(slug: string, change: (root: string) => void = () => {}): {row: HubMotion; gz: Buffer} {
  const dir = mkdtempSync(join(tmpdir(), 'hub-')), root = join(dir, slug);
  for (const [path, data] of toHub(withPoster(slug), {slug, version: '1.0.1', ...ID}).files) {
    mkdirSync(dirname(join(root, path)), {recursive: true});
    writeFileSync(join(root, path), data);
  }
  change(root);
  const gz = execFileSync('tar', ['-czf', '-', '-C', dir, slug]);
  const row: HubMotion = {slug, version: '1.0.1', name: {en: 'Red Pencil'}, line: {en: 'A printed page marked up in red.'}, tags: ['hand-drawn', 'light'],
    authors: ID.authors, license: ID.license, poster: `/m/${slug}/poster.jpg`, tools: existsSync(join(root, 'react')) ? ['react'] : [],
    package: {url: `/m/${slug}/1.0.1.tgz`, sha256: createHash('sha256').update(gz).digest('hex'), bytes: gz.length}};
  return {row, gz};
}
const text = (pack: Map<string,Uint8Array>, path: string) => Buffer.from(pack.get(path)!).toString('utf8');
const config = (pack: Map<string,Uint8Array>) => JSON.parse(text(pack, 'motion/motion.json'));

test('a catalogue motion becomes a pack with the components, theme, caption skin and guidance it was exported from', () => {
  for (const slug of ['red-pencil', 'stage-light', 'on-air', 'field-atlas']) {
    const {row, gz} = hubPackage(slug);
    const pack = packFromPackage(row, gz), builtin = builtinMotion(slug)!;
    for (const [path, data] of builtin) if (/^motion\/(parts|assets|previews)\//.test(path)) assert.ok(Buffer.from(pack.get(path)!).equals(Buffer.from(data)), path);
    assert.ok(![...pack.keys()].some((p) => p.startsWith('motion/demo/')), 'no sample comes back');
    assert.equal(text(pack, 'motion/MOTION.md'), text(builtin, 'motion/MOTION.md').replace(/^<!-- Generated by visotalk[^\n]*\n/m, ''));
    const was = config(builtin).theme.tokens, now = config(pack).theme.tokens;
    assert.deepEqual(now.colors, was.colors, slug);
    assert.deepEqual(now.fonts, was.fonts, slug);
    const {shadow, ...skin} = now.caption, {shadow: shadowWas, ...skinWas} = {background: 'none', ...was.caption};
    assert.deepEqual(skin, skinWas, slug);
    assert.deepEqual(shadow && cssShadow(shadow), shadowWas && cssShadow(shadowWas), slug);
    assert.equal(config(pack).theme.id, config(builtin).theme.id, slug);
    assert.deepEqual(inspectMotion(pack).issues, [], slug);
  }
});

test('a catalogue motion without components is a theme and its guidance; a package is refused when its SHA-256, paths or entries are wrong', () => {
  const bare = hubPackage('red-pencil', (root) => {
    execFileSync('rm', ['-r', join(root, 'react')]);
    writeFileSync(join(root, 'MOTION.md'), '# Paper\n\n## Essence\nx\n## Colour\nx\n## Type\nx\n## Motion\nx\n## Avoid\nx\n');
  });
  const pack = packFromPackage(bare.row, bare.gz);
  assert.deepEqual([...pack.keys()].sort(), ['motion/MOTION.md', 'motion/motion.json', 'motion/poster.jpg']);
  assert.deepEqual(inspectMotion(pack).issues, []);
  const {row, gz} = hubPackage('red-pencil');
  assert.throws(() => packFromPackage({...row, package: {...row.package, sha256: '0'.repeat(64)}}, gz), /SHA-256/);
  const linked = hubPackage('red-pencil', (root) => symlinkSync('/etc/passwd', join(root, 'react', 'parts', 'link.tsx')));
  assert.throws(() => packFromPackage(linked.row, linked.gz), /link/);
  assert.throws(() => packFromPackage({...row, slug: 'another'}, gz), /outside its motion/);
});

test('untar reads a long path through the ustar prefix', () => {
  const dir = mkdtempSync(join(tmpdir(), 'long-')), path = `${'a'.repeat(70)}/${'b'.repeat(70)}/c.txt`;
  mkdirSync(join(dir, dirname(path)), {recursive: true});
  writeFileSync(join(dir, path), 'long');
  const tar = execFileSync('tar', ['--format=ustar', '-cf', '-', '-C', dir, path]);
  assert.equal(Buffer.from(untar(tar).get(path)!).toString(), 'long');
});

test('search matches every word against slugs, names, lines and tags', () => {
  const {row} = hubPackage('red-pencil');
  assert.equal(searchHub([row], ['RED', 'light']).length, 1);
  assert.equal(searchHub([row], ['red', 'dark']).length, 0);
  assert.equal(searchHub([row], []).length, 1);
});

test('a motion is fetched from the catalogue by its slug; an unknown slug is no motion', async () => {
  const {row, gz} = hubPackage('red-pencil');
  const server = createServer((req, res) => {
    if (req.url === '/api/motions.json') { res.setHeader('content-type', 'application/json'); res.end(JSON.stringify({spec: 'motion/0.1', motions: [row]})); }
    else if (req.url === row.package.url) res.end(gz);
    else { res.statusCode = 404; res.end(); }
  });
  await new Promise<void>((done) => server.listen(0, '127.0.0.1', done));
  const base = `http://127.0.0.1:${(server.address() as {port: number}).port}`;
  try {
    assert.deepEqual(inspectMotion((await hubMotion('red-pencil', base))!).issues, []);
    assert.equal(await hubMotion('no-such-motion', base), undefined);
  } finally { server.close(); }
});

test('every built-in pack converts to a motion the catalogue\'s own checker accepts, with nothing of VisoTalk in it', () => {
  for (const slug of ['red-pencil', 'ink-scroll', 'live-studio', 'field-atlas']) {
    const {files} = toHub(withPoster(slug), {slug, version: '1.0.0', ...ID});
    const dir = mkdtempSync(join(tmpdir(), 'share-')), root = join(dir, slug);
    for (const [path, data] of files) { mkdirSync(dirname(join(root, path)), {recursive: true}); writeFileSync(join(root, path), data); }
    assert.deepEqual(checkMotion(root, {author: 'iamsuosi'}), [], slug);
    for (const [path, data] of files) assert.ok(!/visotalk/i.test(path) && (path.endsWith('.jpg') || !/visotalk/i.test(Buffer.from(data).toString('utf8'))), `${slug}: ${path} names VisoTalk`);
    assert.ok([...files.keys()].every((p) => !p.includes('/') || p.startsWith('react/')), `${slug}: only react/ beside the format's files`);
  }
  assert.throws(() => toHub(builtinMotion('red-pencil')!, {slug: 'red-pencil', version: '1.0.0', ...ID}), /no poster/);
});

test('a caption skin becomes the caption tokens a motion carries for other engines', () => {
  assert.deepEqual(cssColor('rgba(12, 13, 15, 0.74)'), {colorSpace: 'srgb', components: [0.0471, 0.051, 0.0588], hex: '#0C0D0F', alpha: 0.74});
  assert.equal(cssColor('linear-gradient(#F4ECD6 0 0) top/100% 4px no-repeat, #1A2233')?.hex, '#1A2233');
  assert.deepEqual(cssShadow('0 2px 12px rgba(0, 0, 0, 0.9), 4px 4px 0 #0B0E14').map((s) => [s.offsetX.value, s.offsetY.value, s.blur.value, s.color?.hex, s.color?.alpha]),
    [[0, 2, 12, '#000000', 0.9], [4, 4, 0, '#0B0E14', undefined]]);
  const t = captionTokens({font: 'display', size: 36, background: 'none', padding: [4, 22], rule: '#F2B33D', ruleSide: 'left'}, {sans: 'Inter'});
  assert.deepEqual(t.font, {$type: 'fontFamily', $value: '{font.sans}'});
  assert.equal(t.background, undefined);
  assert.deepEqual([t['padding-y'], t['rule-left']], [{$type: 'dimension', $value: {value: 4, unit: 'px'}}, {$type: 'color', $value: cssColor('#F2B33D')}]);
});

test('the next version is the next patch, or a new major', () => {
  assert.equal(nextVersion(undefined, 2), '2.0.0');
  assert.equal(nextVersion('1.0.4', 1), '1.0.5');
  assert.equal(nextVersion('1.0.4', 2), '2.0.0');
});

test('sharing writes a checked motion under the person\'s account, and never takes someone else\'s slug', async () => {
  const {row} = hubPackage('red-pencil');
  const published = {spec: 'motion/0.1', slug: 'red-pencil', version: '1.0.1', name: {en: 'Red Pencil'}, line: {en: 'x'}, authors: ID.authors, license: ID.license};
  const server = createServer((req, res) => {
    if (req.url === '/api/motions.json') res.end(JSON.stringify({spec: 'motion/0.1', motions: [{...row, version: '1.0.1'}]}));
    else if (req.url === '/m/red-pencil/motion.json') res.end(JSON.stringify(published));
    else { res.statusCode = 404; res.end(); }
  });
  await new Promise<void>((done) => server.listen(0, '127.0.0.1', done));
  const base = `http://127.0.0.1:${(server.address() as {port: number}).port}`, out = mkdtempSync(join(tmpdir(), 'shared-'));
  try {
    await assert.rejects(shareMotion(withPoster('red-pencil'), {github: 'someone', out: join(out, 'a')}, base), /already published by iamsuosi/);
    const mine = await shareMotion(withPoster('red-pencil'), {github: 'someone', slug: 'my-red-pencil', out: join(out, 'b')}, base);
    assert.match(mine, /my-red-pencil 1\.0\.0 written .* Nothing is published yet/);
    const manifest = JSON.parse(read(join(out, 'b', 'my-red-pencil', 'motion.json'), 'utf8'));
    assert.deepEqual(manifest.authors, [{name: 'someone', github: 'someone'}]);
    assert.match(await shareMotion(withPoster('red-pencil'), {github: 'iamsuosi', out: join(out, 'c')}, base), /red-pencil 1\.0\.2 \(after 1\.0\.1\)/);
    assert.ok(!existsSync(join(out, 'a')), 'a refused share writes nothing');
  } finally { server.close(); }
});
