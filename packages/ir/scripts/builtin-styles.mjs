#!/usr/bin/env node
/**
 * Writes packages/ir/src/builtin-styles.ts from the built-in style packs in skills/visotalk/styles/<slug>/, so the CLI, the web app and the worker
 * copy the same bytes without reading the skill's directory at run time. Every file is kept as base64, so a copy is byte for byte the pack, except
 * its pictures (`poster.jpg`, `previews/`): those are what the galleries show, and the site serves them as files from the skill's directory, so the
 * module stays text however many styles there are. It first rewrites section 8 of each STYLE.md from its components' literal metadata, as `visotalk style check` does in a work.
 * tests/unit/styles.test.ts fails when the module and the directories differ: run this after changing a style.
 *
 *   node packages/ir/scripts/builtin-styles.mjs
 */
import {readdirSync, readFileSync, statSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {styleComponents, styleIndex} from '../src/styles.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
export const STYLES_DIR = join(ROOT, 'skills', 'visotalk', 'styles');
export const MODULE = join(ROOT, 'packages', 'ir', 'src', 'builtin-styles.ts');

/** Every file of every pack, by slug and then by path inside the pack, sorted, hidden files left out; `write` also saves the regenerated section 8 */
export function readPacks(dir = STYLES_DIR, write = false) {
  const packs = {};
  for (const slug of readdirSync(dir).filter((n) => !n.startsWith('.') && statSync(join(dir, n)).isDirectory()).sort()) {
    const files = {};
    const walk = (base) => {
      for (const name of readdirSync(join(dir, slug, base)).sort()) {
        if (name.startsWith('.')) continue;
        const path = base ? `${base}/${name}` : name;
        // a sample's own footage (a style over recordings) stays in the repository for the site's build: a work reads its sample, never plays it
        if (path === 'demo/media') continue;
        // the pictures are the galleries', served by visotalk.dev, not copied into works
        if (path === 'poster.jpg' || path === 'previews') continue;
        if (statSync(join(dir, slug, path)).isDirectory()) walk(path);
        else files[path] = readFileSync(join(dir, slug, path)).toString('base64');
      }
    };
    walk('');
    // an empty directory is not tracked by git, so it is no pack; one with files must be a whole pack
    if (!Object.keys(files).length) continue;
    if (!files['style.json'] || !files['STYLE.md']) throw new Error(`skills/visotalk/styles/${slug} needs style.json and STYLE.md`);
    const {components, issues} = styleComponents(new Map(Object.entries(files).map(([path, data]) => [`style/${path}`, Buffer.from(data, 'base64')])));
    if (issues.length) throw new Error(issues.map((i) => `${slug}/${i.at.slice(6)}: ${i.message}`).join('\n'));
    const guide = styleIndex(Buffer.from(files['STYLE.md'], 'base64').toString('utf8'), components);
    if (write) writeFileSync(join(dir, slug, 'STYLE.md'), guide);
    files['STYLE.md'] = Buffer.from(guide).toString('base64');
    packs[slug] = files;
  }
  return packs;
}

export function render(packs) {
  const body = Object.entries(packs)
    .map(([slug, files]) => `  ${JSON.stringify(slug)}: {\n${Object.entries(files).map(([path, data]) => `    ${JSON.stringify(path)}: ${JSON.stringify(data)},`).join('\n')}\n  },`)
    .join('\n');
  return `/** Generated by packages/ir/scripts/builtin-styles.mjs from skills/visotalk/styles; edit the packs there and run it again. Base64 of every file, by slug and path. */\nexport const BUILTIN_STYLE_FILES: Readonly<Record<string, Readonly<Record<string, string>>>> = {\n${body}\n};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(MODULE, render(readPacks(STYLES_DIR, true)));
  console.log(`wrote ${MODULE}`);
}
